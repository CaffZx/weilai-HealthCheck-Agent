"""模块 4 打分计算器

【业务边界】
输入：已定 S 严重度的异常列表 + 产品标签（定位/阶段/淡旺季）
输出：单异常执行分数、产品执行分数、执行优先级 P0/P1/P2、破平次序号

【规则来源】docs/业务巡检Agent-代码实现版.md §4.0–§4.9
【参数来源】inspector/rules/R4_打分参数.yaml（改数字不改代码）

【数据不足处理】
    不猜、不兜底、不填默认值。任何一处输入缺失都返回"数据不足观察类结果"，
    不进入正式 P0/P1/P2 打分（符合 §3.4 与 §4.0）。

【日志约定】
    每个函数返回 (结果, 日志字典)，日志字典记录：
    - 用了哪些参数值（追溯）
    - 中间计算过程（可复现）
    - 若"数据不足"则说明缺什么
"""
from __future__ import annotations
import logging
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

log = logging.getLogger(__name__)

# -----------------------------------------------------------------------------
# 常量：观察类结果的固定标识（不进入打分）
# -----------------------------------------------------------------------------
观察_数据不足 = "数据不足"


# -----------------------------------------------------------------------------
# 数据契约
# -----------------------------------------------------------------------------
@dataclass
class 异常输入:
    """打分器接受的单个异常输入。字段名对齐 R2 与 R4 契约。"""
    问题点位: str                             # 如 "FBA可售库存为0" "ACOS异常"
    严重度: str                               # "S0" | "S1" | "S2"（必须是正式 S，观察类不传入）
    作用层级: str                             # "链接级" | "变体级"
    变体重要性: str | None = None             # "主要色" | "次要色" | "长尾色"；链接级传 None
    命中对象: str | None = None               # 如 "黑色/M码"；仅日志和展示用


@dataclass
class 产品标签:
    """从 ERP 抓来的产品标签原值（未映射），字段名对齐 MCP/ERP。"""
    产品定位_ERP值: str | None = None         # 如 "P1_PRODUCT"
    产品阶段_ERP值: str | None = None         # 如 "HARVEST_PROFIT" 或中文
    淡旺季_ERP值: str | None = None           # 如 "PEAK_SEASON_PREPARE"


@dataclass
class 打分结果:
    """单异常打分结果。"""
    问题点位: str
    严重度: str
    作用层级: str
    变体重要性: str | None
    命中对象: str | None
    异常基础分: float
    单异常执行分数: float
    公共系数: float
    计算日志: dict = field(default_factory=dict)


@dataclass
class 产品打分结果:
    """父 ASIN 产品级打分结果（多异常聚合）。"""
    产品执行分数: float
    执行优先级: str                           # "P0" | "P1" | "P2"
    处理时限: str                             # "当天处理" | "3天内处理" | "7天内处理"
    父卡严重度: str                           # S0/S1/S2 中最高
    破平次序号: int | None                    # 用于同分排序（None 表示未匹配到任何点位）
    最高单异常: 打分结果
    其余异常: list[打分结果]
    产品定位: str                             # T0-T3（已映射）
    产品阶段: str                             # 已映射的中文
    淡旺季: str                               # 已映射的中文
    公共系数: float                           # 定位 × 阶段 × 淡旺季
    并发权重: float
    计算日志: dict = field(default_factory=dict)


@dataclass
class 观察类结果:
    """数据不足/异常输入无法打分时的输出（不进入正式 P0/P1/P2）。"""
    类型: str = 观察_数据不足
    原因: str = ""
    缺失字段: list[str] = field(default_factory=list)
    上下文: dict = field(default_factory=dict)


# -----------------------------------------------------------------------------
# 参数加载
# -----------------------------------------------------------------------------
_RULES_PATH = Path(__file__).resolve().parent.parent / "rules" / "R4_打分参数.yaml"

_参数缓存: dict | None = None


def 加载参数(force_reload: bool = False) -> dict:
    """加载 R4_打分参数.yaml。启动时读一次，运行时 force_reload 可热重载。"""
    global _参数缓存
    if _参数缓存 is None or force_reload:
        with open(_RULES_PATH, encoding="utf-8") as f:
            _参数缓存 = yaml.safe_load(f)
        log.info("R4 打分参数已加载 版本=%s 源=%s", _参数缓存.get("版本"), _RULES_PATH)
    return _参数缓存


# -----------------------------------------------------------------------------
# 标签映射：ERP 枚举 → 标准中文名
# -----------------------------------------------------------------------------
def 映射产品定位(ERP值: str | None, 参数: dict) -> str | None:
    """P0_PRODUCT → T0；未识别或缺失 → None（数据不足）。"""
    if not ERP值:
        return None
    return 参数["定位ERP映射"].get(ERP值)


def 映射产品阶段(ERP值: str | None, 参数: dict) -> str | None:
    """HARVEST_PROFIT → 收割利润；未识别或缺失 → None。"""
    if not ERP值:
        return None
    return 参数["阶段ERP映射"].get(ERP值)


def 映射淡旺季(ERP值: str | None, 参数: dict) -> str | None:
    """PEAK_SEASON_PREPARE → 旺季前期；未识别或缺失 → None。"""
    if not ERP值:
        return None
    return 参数["淡旺季ERP映射"].get(ERP值)


# -----------------------------------------------------------------------------
# §4.1 异常基础分（严重度 × 变体重要性 二维表）
# -----------------------------------------------------------------------------
def 取异常基础分(严重度: str, 作用层级: str, 变体重要性: str | None, 参数: dict) -> tuple[float | None, str]:
    """按 §4.1 二维表取值。返回 (基础分, 说明)。取不到返回 (None, 缺失原因)。"""
    if 严重度 not in ("S0", "S1", "S2"):
        return None, f"严重度非法：{严重度}（应为 S0/S1/S2）"
    行 = 参数["异常基础分"][严重度]
    if 作用层级 == "链接级":
        return 行["链接级"], f"链接级 {严重度} = {行['链接级']}"
    if 作用层级 == "变体级":
        if not 变体重要性:
            return None, "变体级异常缺少变体重要性数据"
        列名 = f"变体级·{变体重要性}"
        if 列名 not in 行:
            return None, f"变体重要性非法：{变体重要性}（应为 主要色/次要色/长尾色）"
        return 行[列名], f"{列名} {严重度} = {行[列名]}"
    return None, f"作用层级非法：{作用层级}（应为 链接级/变体级）"


# -----------------------------------------------------------------------------
# §4.2/4.3/4.4 系数
# -----------------------------------------------------------------------------
def 取定位系数(定位: str | None, 参数: dict) -> float | None:
    if not 定位 or 定位 not in 参数["产品定位系数"]:
        return None
    return 参数["产品定位系数"][定位]["系数"]


def 取阶段系数(阶段: str | None, 参数: dict) -> float | None:
    if not 阶段 or 阶段 not in 参数["产品阶段系数"]:
        return None
    return 参数["产品阶段系数"][阶段]["系数"]


def 取淡旺季系数(淡旺季: str | None, 参数: dict) -> float | None:
    if not 淡旺季 or 淡旺季 not in 参数["淡旺季系数"]:
        return None
    return 参数["淡旺季系数"][淡旺季]["系数"]


# -----------------------------------------------------------------------------
# §4.6 阈值 → P0/P1/P2 映射
# -----------------------------------------------------------------------------
def 映射优先级(产品执行分数: float, 参数: dict) -> tuple[str, str]:
    """按 §4.6 阈值映射 P 档。返回 (执行优先级, 处理时限)。"""
    阈值 = 参数["执行优先级阈值"]
    if 产品执行分数 >= 阈值["P0"]["分数下限"]:
        return "P0", 阈值["P0"]["处理时限"]
    if 产品执行分数 >= 阈值["P1"]["分数下限"]:
        return "P1", 阈值["P1"]["处理时限"]
    return "P2", 阈值["P2"]["处理时限"]


# -----------------------------------------------------------------------------
# §4.9 破平次序
# -----------------------------------------------------------------------------
def 查破平次序号(问题点位: str, 参数: dict) -> int | None:
    """按 §4.9 表返回该点位的次序号（1-11），未匹配返回 None。"""
    for 次序号, 组 in 参数["破平次序"].items():
        if 问题点位 in 组["包含点位"]:
            return int(次序号)
    return None


# -----------------------------------------------------------------------------
# 严重度大小比较（S0 > S1 > S2）
# -----------------------------------------------------------------------------
_严重度序 = {"S0": 0, "S1": 1, "S2": 2}


def 严重度较高者(a: str, b: str) -> str:
    return a if _严重度序.get(a, 99) <= _严重度序.get(b, 99) else b


# -----------------------------------------------------------------------------
# 主入口 1：算单个异常的执行分数
# -----------------------------------------------------------------------------
def 算单异常分数(
    异常: 异常输入,
    公共系数: float,
    参数: dict,
) -> 打分结果 | 观察类结果:
    """公共系数已算好（定位 × 阶段 × 淡旺季）时的单异常打分。"""
    基础分, 基础分说明 = 取异常基础分(异常.严重度, 异常.作用层级, 异常.变体重要性, 参数)
    if 基础分 is None:
        log.warning("单异常打分-数据不足 点位=%s 原因=%s", 异常.问题点位, 基础分说明)
        return 观察类结果(
            类型=观察_数据不足,
            原因=f"异常「{异常.问题点位}」基础分取值失败：{基础分说明}",
            缺失字段=["变体重要性"] if "变体重要性" in 基础分说明 else ["严重度或作用层级"],
            上下文={"异常": 异常.__dict__},
        )
    单异常分 = round(基础分 * 公共系数, 2)
    return 打分结果(
        问题点位=异常.问题点位,
        严重度=异常.严重度,
        作用层级=异常.作用层级,
        变体重要性=异常.变体重要性,
        命中对象=异常.命中对象,
        异常基础分=基础分,
        单异常执行分数=单异常分,
        公共系数=公共系数,
        计算日志={
            "基础分说明": 基础分说明,
            "公式": f"{基础分} × {公共系数} = {单异常分}",
        },
    )


# -----------------------------------------------------------------------------
# 主入口 2：算产品（父 ASIN）的执行分数与优先级
# -----------------------------------------------------------------------------
def 算产品分数(
    异常列表: list[异常输入],
    产品标签值: 产品标签,
    参数: dict | None = None,
) -> 产品打分结果 | 观察类结果:
    """输入正式异常列表 + 产品标签，输出产品执行分数与优先级。

    数据不足场景（任一发生即返回观察类结果，不进入 P0/P1/P2）：
        - 异常列表为空
        - 产品标签任一字段缺失或无法映射
        - 任一异常无法取到基础分（会记录但继续算其他异常，最终若所有都失败则整体观察）
    """
    if 参数 is None:
        参数 = 加载参数()

    if not 异常列表:
        log.info("算产品分数-无异常")
        return 观察类结果(类型=观察_数据不足, 原因="无正式异常输入")

    # 1. 映射产品标签
    定位 = 映射产品定位(产品标签值.产品定位_ERP值, 参数)
    阶段 = 映射产品阶段(产品标签值.产品阶段_ERP值, 参数)
    淡旺季 = 映射淡旺季(产品标签值.淡旺季_ERP值, 参数)
    缺失 = []
    if not 定位:
        缺失.append(f"产品定位(ERP值={产品标签值.产品定位_ERP值})")
    if not 阶段:
        缺失.append(f"产品阶段(ERP值={产品标签值.产品阶段_ERP值})")
    if not 淡旺季:
        缺失.append(f"淡旺季(ERP值={产品标签值.淡旺季_ERP值})")
    if 缺失:
        log.warning("算产品分数-标签数据不足 缺失=%s", 缺失)
        return 观察类结果(
            类型=观察_数据不足,
            原因="产品标签缺失或未识别，无法计算公共系数",
            缺失字段=缺失,
            上下文={"产品标签": 产品标签值.__dict__},
        )

    # 2. 公共系数
    定位系数 = 取定位系数(定位, 参数)
    阶段系数 = 取阶段系数(阶段, 参数)
    淡旺季系数 = 取淡旺季系数(淡旺季, 参数)
    公共系数 = round(定位系数 * 阶段系数 * 淡旺季系数, 6)

    # 3. 逐异常打分
    单异常结果列表: list[打分结果] = []
    数据不足详情: list[str] = []
    for 异常 in 异常列表:
        r = 算单异常分数(异常, 公共系数, 参数)
        if isinstance(r, 打分结果):
            单异常结果列表.append(r)
        else:
            数据不足详情.append(f"{异常.问题点位}: {r.原因}")

    if not 单异常结果列表:
        return 观察类结果(
            类型=观察_数据不足,
            原因="所有异常均无法打分",
            缺失字段=数据不足详情,
        )

    # 4. 聚合：最高分 + 其余 × 并发权重
    并发权重 = 参数["并发权重"]["默认"]
    单异常结果列表.sort(key=lambda r: r.单异常执行分数, reverse=True)
    最高 = 单异常结果列表[0]
    其余 = 单异常结果列表[1:]
    产品分 = round(最高.单异常执行分数 + sum(r.单异常执行分数 * 并发权重 for r in 其余), 2)

    # 5. 映射优先级
    执行优先级, 处理时限 = 映射优先级(产品分, 参数)

    # 6. 父卡严重度：所有子异常中最高的
    父卡严重度 = 单异常结果列表[0].严重度
    for r in 单异常结果列表[1:]:
        父卡严重度 = 严重度较高者(父卡严重度, r.严重度)

    # 7. 破平次序号（取次序号最小者，§4.9）
    次序候选 = [
        n for n in (查破平次序号(r.问题点位, 参数) for r in 单异常结果列表) if n is not None
    ]
    破平次序号 = min(次序候选) if 次序候选 else None

    结果 = 产品打分结果(
        产品执行分数=产品分,
        执行优先级=执行优先级,
        处理时限=处理时限,
        父卡严重度=父卡严重度,
        破平次序号=破平次序号,
        最高单异常=最高,
        其余异常=其余,
        产品定位=定位,
        产品阶段=阶段,
        淡旺季=淡旺季,
        公共系数=公共系数,
        并发权重=并发权重,
        计算日志={
            "公式": f"{最高.单异常执行分数} + Σ({[r.单异常执行分数 for r in 其余]}) × {并发权重} = {产品分}",
            "标签映射": {"定位": 定位, "阶段": 阶段, "淡旺季": 淡旺季},
            "系数": {"定位系数": 定位系数, "阶段系数": 阶段系数, "淡旺季系数": 淡旺季系数, "公共系数": 公共系数},
            "参数版本": 参数.get("版本"),
            "数据不足的异常": 数据不足详情 if 数据不足详情 else None,
        },
    )
    log.info(
        "算产品分数完成 产品分=%s 优先级=%s 父卡严重度=%s 异常数=%s 数据不足异常数=%s",
        产品分, 执行优先级, 父卡严重度, len(单异常结果列表), len(数据不足详情),
    )
    return 结果


# -----------------------------------------------------------------------------
# 便捷函数：跑 yaml 内置单元测试算例（§4.8）
# -----------------------------------------------------------------------------
def 跑内置算例() -> list[tuple[str, bool, Any]]:
    """跑 yaml 里 单元测试算例 定义的所有算例，返回 [(名称, 通过, 详情), ...]"""
    参数 = 加载参数(force_reload=True)
    输出 = []
    for 算例 in 参数.get("单元测试算例", []):
        名称 = 算例["名称"]
        p = 算例["输入产品"]
        # 从 yaml 里反查 ERP 枚举（拿第一个）
        定位ERP = 参数["产品定位系数"][p["定位"]]["ERP枚举"]
        阶段ERP = 参数["产品阶段系数"][p["阶段"]]["ERP枚举"]
        淡旺季ERP = 参数["淡旺季系数"][p["淡旺季"]]["ERP枚举"]
        产品 = 产品标签(
            产品定位_ERP值=定位ERP if isinstance(定位ERP, str) else 定位ERP[0],
            产品阶段_ERP值=阶段ERP if isinstance(阶段ERP, str) else 阶段ERP[0],
            淡旺季_ERP值=淡旺季ERP if isinstance(淡旺季ERP, str) else 淡旺季ERP[0],
        )
        异常列表 = [
            异常输入(
                问题点位=a["点位"],
                严重度=a["严重度"],
                作用层级=a["作用层级"],
                变体重要性=a.get("变体重要性"),
            )
            for a in 算例["输入异常"]
        ]
        结果 = 算产品分数(异常列表, 产品, 参数)
        if isinstance(结果, 观察类结果):
            输出.append((名称, False, f"意外返回数据不足: {结果.原因}"))
            continue
        通过 = (
            abs(结果.产品执行分数 - 算例["预期产品执行分数"]) < 0.01
            and 结果.执行优先级 == 算例["预期执行优先级"]
            and 结果.父卡严重度 == 算例["预期父卡严重度"]
        )
        输出.append((
            名称,
            通过,
            {
                "产品执行分数": f"{结果.产品执行分数} (期望 {算例['预期产品执行分数']})",
                "执行优先级": f"{结果.执行优先级} (期望 {算例['预期执行优先级']})",
                "父卡严重度": f"{结果.父卡严重度} (期望 {算例['预期父卡严重度']})",
            },
        ))
    return 输出


