# §3.11 退款异常（双基准，取高）
# -----------------------------------------------------------------------------
def 判退款异常(
    十六周退款率: float | None,
    三十二周退款率: float | None,
    类目平均退换货率: float | None,
    本周订单商品总数: int | None,
    上周订单商品总数: int | None = None,
    参数: dict | None = None,
) -> 严重度判定结果 | 观察类结果:
    """§3.11 退款异常。数据完整性 + 样本量 + 双基准取高。
    口径：ERP 无"本周/上周"退款率，改用 16周 vs 32周 判长趋势。"""
    if 参数 is None:
        参数 = 加载参数()
    cfg = 参数["退款异常"]

    # 数据完整性：16周与32周均需有正常退款率
    if 十六周退款率 is None or 三十二周退款率 is None:
        return 观察类结果(问题点位="退款异常", 观察类型=观察_数据不足,
                     原因=cfg["数据不足输出"],
                     缺失字段=[k for k, v in {"16周退款率": 十六周退款率, "32周退款率": 三十二周退款率}.items() if v is None])

    # 样本量：本周订单 >= 20 或 本周+上周 >= 30
    满足样本 = (本周订单商品总数 is not None and 本周订单商品总数 >= 20) or (
        (本周订单商品总数 or 0) + (上周订单商品总数 or 0) >= 30
    )
    if not 满足样本:
        return 观察类结果(问题点位="退款异常", 观察类型=观察_样本不足观察,
                     原因=cfg["样本不足输出"],
                     上下文={"本周订单": 本周订单商品总数, "上周订单": 上周订单商品总数})

    # 基准 A：16周 vs 32周（相对上升，长趋势）
    严重度A = None
    分档A = "未参与"
    if 三十二周退款率 > 0:
        上升A = (十六周退款率 - 三十二周退款率) / 三十二周退款率
        严重度A, 分档A, _ = _落档(上升A, cfg["基准A_分档"], "上升")

    # 基准 B：16周 vs 类目均值（倍数）
    严重度B = None
    分档B = "未参与"
    if 类目平均退换货率 is not None and 类目平均退换货率 > 0:
        倍数 = 十六周退款率 / 类目平均退换货率
        严重度B, 分档B, _ = _落档(倍数, cfg["基准B_分档"], "倍数")

    最终 = 严重度较高者(严重度A, 严重度B)
    if 最终 is None:
        return 严重度判定结果(问题点位="退款异常", 严重度=None,  # type: ignore
                        判定过程=f"两基准均不预警（A:{分档A}, B:{分档B}）",
                        分档名称=f"A:{分档A}|B:{分档B}",
                        命中值={"16周退款率": 十六周退款率, "32周退款率": 三十二周退款率, "类目均值": 类目平均退换货率})

    return 严重度判定结果(
        问题点位="退款异常",
        严重度=最终,
        判定过程=f"16周退款率 {十六周退款率:.1f}%，超阈值触发（{分档A}/{分档B} → {最终}）",
        分档名称=f"A:{分档A}|B:{分档B}",
        命中值={"16周退款率": 十六周退款率, "32周退款率": 三十二周退款率, "类目均值": 类目平均退换货率},
        数据快照=[
            _kv_percent("16周退款率", 十六周退款率),
            _kv_percent("32周退款率", 三十二周退款率),
            _kv_percent("类目平均退款率", 类目平均退换货率),
            _kv_int("本周订单数", 本周订单商品总数),
            _kv_int("上周订单数", 上周订单商品总数),
            _kv("对比32周指标", 分档A),
            _kv("对比类目指标", 分档B),
        ],
    )


