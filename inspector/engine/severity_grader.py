# 单元测试：跑 yaml 里的算例
# -----------------------------------------------------------------------------
def 跑内置算例() -> list[tuple[str, bool, Any]]:
    参数 = 加载参数(force_reload=True)
    输出 = []
    for 算例 in 参数.get("单元测试算例", []):
        名称 = 算例["场景"]
        专项名 = 算例["专项"]
        输入 = 算例["输入"]

        if 专项名 == "ACOS异常":
            r = 判ACOS异常(**输入, 参数=参数)
        elif 专项名 == "销量异常_下降":
            r = 判销量类异常(**输入, 参数=参数)
        elif 专项名 == "库存积压":
            # yaml 里的输入需要转换为函数参数
            可售库存 = 输入["可售库存"]
            近30天日均销量 = 输入["近30天日均销量"]
            未来2月 = 输入.get("未来2月目标累计")
            覆盖月数 = 可售库存 / (未来2月 / 2) if 未来2月 else None
            r = 判库存积压(
                可售库存=可售库存,
                近30天日均销量=近30天日均销量,
                未来N月目标累计_覆盖月数=覆盖月数,
                参数=参数,
            )
        else:
            输出.append((名称, False, f"未支持的专项: {专项名}"))
            continue

        期望S = 算例.get("预期严重度")
        期望观察 = 算例.get("预期观察类")

        if 期望观察:
            通过 = isinstance(r, 观察类结果) and 期望观察 in r.原因
            细 = f"实际={r.观察类型 if isinstance(r, 观察类结果) else '未观察'} / 期望包含={期望观察}"
        else:
            实际S = r.严重度 if isinstance(r, 严重度判定结果) else None
            通过 = 实际S == 期望S
            细 = f"实际={实际S} / 期望={期望S}"

        输出.append((名称, 通过, 细))
    return 输出


