# §3.10 链接转化率异常（双基准，取高）
# -----------------------------------------------------------------------------
def 判链接转化率异常(
    本周转化率: float | None,
    上周转化率: float | None,
    类目平均转化率: float | None,
    本周会话: int | None,
    上周会话: int | None = None,
    本周订单商品总数: int | None = None,
    上周订单商品总数: int | None = None,
    参数: dict | None = None,
) -> 严重度判定结果 | 观察类结果:
    """§3.10 转化率异常。空值不判、双基准取高、样本量门槛。"""
    if 参数 is None:
        参数 = 加载参数()
    cfg = 参数["链接转化率异常下降"]

    # 空值不判定（注意：0 是有效值，不是空）
    if 本周转化率 is None or 类目平均转化率 is None:
        return 观察类结果(问题点位="链接转化率异常下降", 观察类型=观察_待数据积累,
                     原因="本周转化率或类目均值为空/未生成",
                     缺失字段=[k for k, v in {"本周转化率": 本周转化率, "类目平均转化率": 类目平均转化率}.items() if v is None])

    # 样本量门槛
    if 本周会话 is None:
        return 观察类结果(问题点位="链接转化率异常下降", 观察类型=观察_数据不足,
                     原因="缺失本周会话数据", 缺失字段=["本周会话"])

    if 本周会话 < 100:
        # 观察阈值：会话<100 但 本周+上周订单商品总数 >=10 → 观察
        if (本周订单商品总数 or 0) + (上周订单商品总数 or 0) >= 10:
            return 观察类结果(问题点位="链接转化率异常下降", 观察类型=观察_样本不足观察,
                         原因=f"本周会话 {本周会话} < 100，进入{cfg['观察输出']}",
                         上下文={"本周订单": 本周订单商品总数, "上周订单": 上周订单商品总数})
        return 观察类结果(问题点位="链接转化率异常下降", 观察类型=观察_样本不足观察,
                     原因=f"本周会话 {本周会话} < 100，不满足样本量门槛")

    # 基准 A：本周 vs 上周（降幅）
    严重度A = None
    分档A = "未参与"
    if 上周转化率 is not None and 上周会话 is not None and 上周会话 >= 1:
        if 上周转化率 > 0:
            降幅A = (上周转化率 - 本周转化率) / 上周转化率
            严重度A, 分档A, _ = _落档(降幅A, cfg["基准A_分档"], "降幅")

    # 基准 B：本周 vs 类目均值（比例）
    严重度B = None
    分档B = "未参与"
    if 类目平均转化率 > 0:
        比例B = 本周转化率 / 类目平均转化率
        严重度B, 分档B, _ = _落档(比例B, cfg["基准B_分档"], "比例")

    最终 = 严重度较高者(严重度A, 严重度B)
    if 最终 is None:
        return 严重度判定结果(问题点位="链接转化率异常下降", 严重度=None,  # type: ignore
                        判定过程=f"两基准均不预警（A:{分档A}, B:{分档B}）",
                        分档名称=f"A:{分档A}|B:{分档B}",
                        命中值={"基准A严重度": 严重度A, "基准B严重度": 严重度B})

    return 严重度判定结果(
        问题点位="链接转化率异常下降",
        严重度=最终,
        判定过程=f"两项指标共同判定：{分档A} / {分档B}（→ {最终}）",
        分档名称=f"A:{分档A}|B:{分档B}",
        命中值={"基准A严重度": 严重度A, "基准B严重度": 严重度B},
        数据快照=[
            _kv_pct("本周转化率", 本周转化率),
            _kv_pct("上周转化率", 上周转化率),
            _kv_pct("类目平均转化率", 类目平均转化率),
            _kv_int("本周会话", 本周会话),
            _kv_int("上周会话", 上周会话),
            _kv("对比周指标", f"{分档A}"),
            _kv("对比类目指标", f"{分档B}"),
        ],
    )


