def 判滞销异常(
    有滞销库存: bool,
    命中子ASIN滞销库存: float | None,
    命中子ASIN近30天日均销量: float | None,
    父ASIN汇总单月超龄仓租费用: float | None,
    命中子ASIN近30天累计订单: float | None = None,
    命中子ASIN销量覆盖天数: int | None = None,
    命中子ASIN销量数据截止日: str | None = None,
    参数: dict | None = None,
) -> 严重度判定结果 | 观察类结果:
    """§3.14 滞销异常。3 条准入 + 消化周期分档。"""
    if 参数 is None:
        参数 = 加载参数()
    cfg = 参数["滞销异常"]

    # 准入条件 1：有滞销库存
    if not 有滞销库存:
        return 严重度判定结果(问题点位="滞销异常", 严重度=None,  # type: ignore
                        判定过程="无滞销库存，不进入判定", 分档名称="未进入")

    # 数据完整性
    缺 = [k for k, v in {"命中子ASIN滞销库存": 命中子ASIN滞销库存,
                        "父ASIN汇总单月超龄仓租费用": 父ASIN汇总单月超龄仓租费用}.items() if v is None]
    if 缺:
        return 观察类结果(问题点位="滞销异常", 观察类型=观察_数据不足,
                     原因="数据完整性不足", 缺失字段=缺)

    # 准入条件 3：超龄费达规模
    阈值USD = cfg["准入条件"][2]["阈值_USD"]
    if 父ASIN汇总单月超龄仓租费用 <= 阈值USD:
        return 严重度判定结果(问题点位="滞销异常", 严重度=None,  # type: ignore
                        判定过程=f"超龄费 ${父ASIN汇总单月超龄仓租费用} <= ${阈值USD}，未达规模",
                        分档名称="超龄费未达规模")

    # 消化周期
    if 命中子ASIN近30天日均销量 is None:
        return 观察类结果(问题点位="滞销异常", 观察类型=观察_数据不足,
                     原因="命中子ASIN 近30天日均销量为空",
                     缺失字段=["命中子ASIN近30天日均销量"])
    if 命中子ASIN近30天日均销量 == 0:
        消化周期 = 999
    else:
        消化周期 = 命中子ASIN滞销库存 / 命中子ASIN近30天日均销量

    # 准入条件 2：1 个月消化不完
    if 消化周期 <= 30:
        return 严重度判定结果(问题点位="滞销异常", 严重度=None,  # type: ignore
                        判定过程=f"消化周期 {消化周期:.1f} 天 <= 30 天，不进入判定",
                        分档名称="消化不足30天")

    # 分档
    严重度, 分档名, _ = _落档(消化周期, cfg["分档"], "消化周期")
    if 严重度 is None:
        return 严重度判定结果(问题点位="滞销异常", 严重度=None,  # type: ignore
                        判定过程=f"消化周期 {消化周期:.1f} 天，未落档", 分档名称=分档名)

    evidence = ""
    if 命中子ASIN销量覆盖天数 is not None:
        evidence = f"；近30天覆盖 {命中子ASIN销量覆盖天数} 天"
        if 命中子ASIN近30天累计订单 is not None:
            evidence += f"，累计订单 {命中子ASIN近30天累计订单:g}"
        evidence += f"，日均 {命中子ASIN近30天日均销量:g}"
        if 命中子ASIN销量数据截止日:
            evidence += f"，数据截至 {命中子ASIN销量数据截止日}"
    return 严重度判定结果(
        问题点位="滞销异常",
        严重度=严重度,
        判定过程=f"消化周期 {消化周期:.1f} 天（{分档名}）→ {严重度}{evidence}",
        分档名称=分档名,
        命中值=round(消化周期, 1),
    )


