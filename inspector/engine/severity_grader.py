def 加载参数(force_reload: bool = False) -> dict:
    """加载 R3_严重度阈值.yaml。启动时读一次，force_reload=True 热重载。"""
    global _参数缓存
    if _参数缓存 is None or force_reload:
        with open(_RULES_PATH, encoding="utf-8") as f:
            _参数缓存 = yaml.safe_load(f)
        log.info("R3 严重度阈值已加载 版本=%s", _参数缓存.get("版本"))
    return _参数缓存


# -----------------------------------------------------------------------------
# 数据快照工具：把结构化数据点包装成前端友好的 label/value 列表
# -----------------------------------------------------------------------------
def _kv(label: str, value, kind: str = "kv") -> dict:
    """单个字段-值。value 可以是 float/int/str/None，自动格式化。"""
    return {"label": label, "value": _fmt_val(value), "kind": kind}


def _fmt_val(v) -> str:
    """自动格式化：None→—；float 0-1（比例可能）→保留 2 位；int→整数。
    百分比字段名的判断在 _kv_pct 里显式做，这里做通用兜底。"""
    if v is None:
        return "—"
    if isinstance(v, bool):
        return "是" if v else "否"
    if isinstance(v, float):
        return f"{v:.2f}".rstrip("0").rstrip(".")
    return str(v)


def _kv_pct(label: str, v) -> dict:
    """百分比字段（输入为比率 0.4 → 40.0%）"""
    if v is None:
        return {"label": label, "value": "—", "kind": "kv"}
    return {"label": label, "value": f"{v * 100:.1f}%", "kind": "kv"}


def _kv_percent(label: str, v) -> dict:
    """百分比字段（输入已是百分比数值 24.0 → 24.0%，不再乘 100）"""
    if v is None:
        return {"label": label, "value": "—", "kind": "kv"}
    return {"label": label, "value": f"{v:.1f}%", "kind": "kv"}


def _kv_money(label: str, v) -> dict:
    """金额字段：12.345 → $12.35"""
    if v is None:
        return {"label": label, "value": "—", "kind": "kv"}
    return {"label": label, "value": f"${v:.2f}", "kind": "kv"}


def _kv_int(label: str, v) -> dict:
    """整数字段：12.7 → 13"""
    if v is None:
        return {"label": label, "value": "—", "kind": "kv"}
    try:
        return {"label": label, "value": str(int(round(float(v)))), "kind": "kv"}
    except (TypeError, ValueError):
        return {"label": label, "value": str(v), "kind": "kv"}


def _series_pct(label: str, series: list, days: int = 7) -> dict:
    """把逐日百分比序列格式化：[0.35, 0.42, ...] → "7/6:35.0% 7/7:42.0% ..." """
    if not series:
        return {"label": label, "value": "", "kind": "series"}
    today = _dt.date.today()
    parts = []
    n = min(len(series), days)
    for i, v in enumerate(series[-n:]):
        # 序列末尾是最近一天；末尾第 j 个对应"今天前 (n-1-j) 天"
        d = today - _dt.timedelta(days=(n - i))
        val = f"{v * 100:.1f}%" if v is not None else "—"
        parts.append(f"{d.month}/{d.day}:{val}")
    return {"label": label, "value": " · ".join(parts), "kind": "series"}


def _series_num(label: str, series: list, days: int = 7, fmt: str = "{:.1f}") -> dict:
    """把逐日数值序列格式化：[3, 5, 8, ...] → "7/6:3 7/7:5 ..."""
    if not series:
        return {"label": label, "value": "", "kind": "series"}
    today = _dt.date.today()
    parts = []
    n = min(len(series), days)
    for i, v in enumerate(series[-n:]):
        d = today - _dt.timedelta(days=(n - i))
        val = fmt.format(v) if v is not None else "—"
        # 去掉多余 .0
        if val.endswith(".0"):
            val = val[:-2]
        parts.append(f"{d.month}/{d.day}:{val}")
    return {"label": label, "value": " · ".join(parts), "kind": "series"}


# -----------------------------------------------------------------------------
# 通用工具：落档
# -----------------------------------------------------------------------------
_严重度序 = {"S0": 0, "S1": 1, "S2": 2}


def 严重度较高者(a: str | None, b: str | None) -> str | None:
    """S0 > S1 > S2 > null"""
    if a is None:
        return b
    if b is None:
        return a
    return a if _严重度序[a] <= _严重度序[b] else b


def _落档(数值: float, 分档表: list, 值字段前缀: str) -> tuple[str | None, str, dict]:
    """在分档表里找到 数值 所属的档位。

    分档表约定：每档有 <前缀>_下限、<前缀>_上限（null=±∞）；下限含、上限不含。
    返回：(严重度|None, 分档名称, 匹配的档配置)
    """
    下限键 = f"{值字段前缀}_下限"
    上限键 = f"{值字段前缀}_上限"
    for 档 in 分档表:
        下限 = 档.get(下限键)
        上限 = 档.get(上限键)
        if 下限 is None:
            下限 = -math.inf
        if 上限 is None:
            上限 = math.inf
        if 下限 <= 数值 < 上限:
            return 档["严重度"], 档["名称"], 档
    return None, "未命中任何档", {}


