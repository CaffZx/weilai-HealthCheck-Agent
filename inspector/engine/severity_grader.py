"""模块 3 严重度判定器

【业务边界】
输入：命中的异常点位 + 该点位所需的数据字段
输出：正式严重度 S0/S1/S2 → 进入 R4 打分
     或观察类结果（数据不足/样本不足观察/待数据积累）→ 不打分、只标记

【规则来源】docs/业务巡检Agent-代码实现版.md 模块 3
【参数来源】inspector/rules/R3_严重度阈值.yaml（改数字不改代码）

【设计约定】
1. 一个专项一个函数（高内聚），互相不 import（低耦合）
2. 分档统一走 _落档() 工具，读 yaml 的 { X_下限, X_上限 } 结构
3. 数据不足 = 明确返回观察类结果，绝不猜、不填默认值
4. 每个函数返回 严重度判定结果 或 观察类结果，都带 判定过程 字段（人话）
5. 双基准类（转化率/评分/退款）：两个基准各算一档，取严重度较高
"""
from __future__ import annotations

import datetime as _dt
import logging
import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

log = logging.getLogger(__name__)

观察_数据不足 = "数据不足"
观察_样本不足观察 = "样本不足观察"
观察_待数据积累 = "待数据积累"


# -----------------------------------------------------------------------------
# 数据契约
# -----------------------------------------------------------------------------
@dataclass
class 严重度判定结果:
    """正式判定结果，可进入 R4 打分。"""
    问题点位: str
    严重度: str                          # "S0" | "S1" | "S2"
    判定过程: str                        # 一句人话结论（判据/结论）
    分档名称: str                        # 命中的分档名（如 "超出60-100"）
    命中值: Any = None                   # 触发的实际数值（如偏离比 0.7）
    判定日志: dict = field(default_factory=dict)
    # 数据快照：结构化的支撑证据 —— 判据是"结论"、数据快照是"数字"，两者互补不重复
    # 格式：list[dict]，每 dict 是 {"label": "字段名", "value": "格式化后的值", "kind": "kv|series"}
    # kind=kv → 单一字段-值；kind=series → 逐日序列（value 是 "M/D:xx  M/D:xx" 拼接后字符串）
    数据快照: list = field(default_factory=list)


@dataclass
class 观察类结果:
    """数据不足/样本不足/待数据积累时的输出（不进入打分）。"""
    问题点位: str
    观察类型: str                        # 观察_数据不足 / 观察_样本不足观察 / 观察_待数据积累
    原因: str
    缺失字段: list[str] = field(default_factory=list)
    上下文: dict = field(default_factory=dict)


