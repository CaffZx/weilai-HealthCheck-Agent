# §3.12 放量未执行（5 条件全满足）
# -----------------------------------------------------------------------------
def 判放量未执行(
    近7天日均销量: float | None,
    日均目标单量: float | None,
    可售库存: float | None,
    近7天平均ACOS: float | None,          # 与判ACOS异常统一命名
    目标ACOS: float | None,
    近3天平均花费: float | None,           # 与判广告花费异常统一命名
    近7天平均花费: float | None,
    近7天平均自然占比: float | None,        # 与判自然流量异常统一命名
    前7天平均自然占比: float | None,
    近3天平均自然占比: float | None,
    参数: dict | None = None,
) -> 严重度判定结果 | 观察类结果:
    """§3.12 放量未执行。5 条件全部满足才触发 S1。
    参数命名与 R3 其他专项函数统一（近7天平均ACOS / 近3天平均花费 / 近7天平均自然占比）"""
    if 参数 is None:
        参数 = 加载参数()
    cfg = 参数["放量未执行"]

    # ACOS 数据不足边界
    if 近7天平均ACOS is None or 目标ACOS is None:
        return 观察类结果(问题点位="放量未执行", 观察类型=观察_数据不足,
                     原因=cfg["数据不足输出"],
                     缺失字段=[k for k, v in {"近7天平均ACOS": 近7天平均ACOS, "目标ACOS": 目标ACOS}.items() if v is None])

    结果每条件 = []

    # 条件 1：销量达标
    条件1 = 近7天日均销量 is not None and 日均目标单量 is not None and 近7天日均销量 >= 日均目标单量
    结果每条件.append(("销量达标", 条件1))

    # 条件 2：库存充足（可售库存 >= 日均单量 * 1.2 * 30）
    if 可售库存 is not None and 近7天日均销量 is not None:
        条件2 = 可售库存 >= 近7天日均销量 * 1.2 * 30
    else:
        条件2 = False
    结果每条件.append(("库存充足", 条件2))

    # 条件 3：ACOS 健康
    条件3 = 近7天平均ACOS < 目标ACOS
    结果每条件.append(("ACOS健康", 条件3))

    # 条件 4：广告未放量
    if 近3天平均花费 is not None and 近7天平均花费 is not None:
        条件4 = 近3天平均花费 <= 近7天平均花费 * 1.1
    else:
        条件4 = False
    结果每条件.append(("广告未放量", 条件4))

    # 条件 5：自然占比上涨
    if all(v is not None for v in [近7天平均自然占比, 前7天平均自然占比, 近3天平均自然占比]):
        条件5 = (近7天平均自然占比 > 前7天平均自然占比) and (近3天平均自然占比 >= 近7天平均自然占比)
    else:
        条件5 = False
    结果每条件.append(("自然占比上涨", 条件5))

    全部满足 = all(v for _, v in 结果每条件)
    未满足 = [名 for 名, v in 结果每条件 if not v]

    if not 全部满足:
        return 严重度判定结果(问题点位="放量未执行", 严重度=None,  # type: ignore
                        判定过程=f"5 条件未全满足，未满足项: {未满足}",
                        分档名称="条件未全满足",
                        命中值=dict(结果每条件))

    return 严重度判定结果(
        问题点位="放量未执行",
        严重度=cfg["默认严重度"],
        判定过程="5 条件全部满足",
        分档名称="全部满足",
        命中值=dict(结果每条件),
    )


