# §3.11 评分异常（双基准，取高）
# -----------------------------------------------------------------------------
def 判评分异常(
    当前评分: float | None,
    近7天平均评分: float | None,
    目标评分: float | None = None,
    参数: dict | None = None,
) -> 严重度判定结果 | 观察类结果:
    """§3.11 评分异常。空值不判、双基准取高。"""
    if 参数 is None:
        参数 = 加载参数()
    cfg = 参数["评分异常"]

    if 当前评分 is None:
        return 观察类结果(问题点位="评分异常", 观察类型=观察_待数据积累,
                     原因="当前评分为空/未生成", 缺失字段=["当前评分"])

    # 基准 A：当前 vs 近7天均
    严重度A = None
    分档A = "未参与"
    if 近7天平均评分 is not None:
        下降A = 近7天平均评分 - 当前评分
        if 下降A < 0:
            下降A = 0  # 上升方向不算异常
        严重度A, 分档A, _ = _落档(下降A, cfg["基准A_分档"], "下降")

    # 基准 B：当前 vs 目标
    严重度B = None
    分档B = "未参与"
    if 目标评分 is not None:
        if 当前评分 >= 目标评分:
            分档B = "达标"
        else:
            分档B = "低于目标"
            严重度B = "S1"

