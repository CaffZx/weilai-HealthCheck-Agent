def 判自然流量异常(
    近3天平均自然占比: float | None,
    近7天平均自然占比: float | None,
    近3天自然订单数: float | None = None,     # 用于被动下降判断
    近7天自然订单数: float | None = None,
    近7天逐日自然占比: list[float] | None = None,   # S0 升级
    前7天平均自然占比: float | None = None,
    参数: dict | None = None,
) -> 严重度判定结果 | 观察类结果:
    """§3.8 自然流量。占比是 0-1 小数；下降幅度按百分点计。"""
    if 参数 is None:
        参数 = 加载参数()

    缺 = [k for k, v in {"近3天平均自然占比": 近3天平均自然占比,
                        "近7天平均自然占比": 近7天平均自然占比}.items() if v is None]
    if 缺:
        return 观察类结果(问题点位="自然流量异常", 观察类型=观察_数据不足,
                     原因=f"缺失字段 {缺}", 缺失字段=缺)

    cfg = 参数["自然流量异常"]

    # 被动下降豁免：自然订单数没降，只是总订单涨 → 不直接判
    if (cfg.get("被动下降豁免") and 近3天自然订单数 is not None and 近7天自然订单数 is not None
        and 近3天自然订单数 >= 近7天自然订单数):
        return 严重度判定结果(问题点位="自然流量异常", 严重度=None,  # type: ignore
                        判定过程="被动下降豁免：自然订单未降，转 §6.0.8 查证",
                        分档名称="被动下降豁免",
                        命中值={"近3天自然订单数": 近3天自然订单数, "近7天自然订单数": 近7天自然订单数})

    # 下降百分点 = 基线 - 当前（单位：百分点）
    下降百分点 = (近7天平均自然占比 - 近3天平均自然占比) * 100
    严重度, 分档名, _ = _落档(下降百分点, cfg["分档"], "下降百分点")

    # S0 升级
    if 严重度 is not None and 前7天平均自然占比 is not None and 近7天逐日自然占比 and len(近7天逐日自然占比) >= 7:
        if all(v < 前7天平均自然占比 for v in 近7天逐日自然占比[-7:]):
            return 严重度判定结果(
                问题点位="自然流量异常",
                严重度="S0",
                判定过程="S0 升级：近7天内逐日自然占比均低于前7天基线，连续7天",
                分档名称="S0升级",
                命中值=round(下降百分点, 2),
            )

    if 严重度 is None:
        return 严重度判定结果(问题点位="自然流量异常", 严重度=None,  # type: ignore
                        判定过程=f"下降 {下降百分点:.1f}pp（{分档名}），不预警",
                        分档名称=分档名, 命中值=round(下降百分点, 2))

    return 严重度判定结果(
        问题点位="自然流量异常",
        严重度=严重度,
        判定过程=f"近 3 天自然占比 {近3天平均自然占比:.1%}，7 天平均 {近7天平均自然占比:.1%}，下降 {下降百分点:.1f} 个百分点（{分档名}）",
        数据快照=[
            _kv_pct("近 3 天自然占比", 近3天平均自然占比),
            _kv_pct("近 7 天自然占比", 近7天平均自然占比),
            _kv("下降幅度", f"{下降百分点:.1f} 个百分点"),
            _kv("近 3 天自然订单", str(int(近3天自然订单数)) if 近3天自然订单数 is not None else "—"),
            _kv("近 7 天自然订单", str(int(近7天自然订单数)) if 近7天自然订单数 is not None else "—"),
            _series_pct("近 7 天逐日自然占比", 近7天逐日自然占比 or [], days=7) if 近7天逐日自然占比 else _kv("近 7 天逐日自然占比", "—"),
        ],
        分档名称=分档名,
        命中值=round(下降百分点, 2),
    )


