# §3.13 库存积压（A × B 交叉 + 降档）
# -----------------------------------------------------------------------------
def 判库存积压(
    可售库存: float | None,
    近30天日均销量: float | None,
    未来N月目标累计_覆盖月数: float | None,     # 已算好的 可售库存/月目标 覆盖月数
    是否新品观察期: bool = False,
    有效销售天数: int | None = None,           # < 7 天视为新品观察
    参数: dict | None = None,
) -> 严重度判定结果 | 观察类结果:
    """§3.13 库存积压。A 可售天数 + B 目标累计月数 交叉。"""
    if 参数 is None:
        参数 = 加载参数()
    cfg = 参数["库存积压"]

    # 数据完整性
    if 可售库存 is None:
        return 观察类结果(问题点位="库存积压", 观察类型=观察_数据不足,
                     原因=cfg["数据不足输出"], 缺失字段=["可售库存"])

    # 新品观察期
    if 是否新品观察期 or (有效销售天数 is not None and 有效销售天数 < 7):
        return 观察类结果(问题点位="库存积压", 观察类型=观察_数据不足,
                     原因="新品库存压力待观察", 上下文={"有效销售天数": 有效销售天数})

    # A：可售天数（A_可判 表示数据够，可以落档；A严重度=None 表示不预警档；两者独立）
    if 近30天日均销量 is None:
        A_可判 = False
        A严重度 = None
        A分档 = "A数据缺失"
        可售天数 = None
    elif 近30天日均销量 == 0:
        # 非新品且日均=0 且有库存 → >120天，A档 S0
        A_可判 = True
        可售天数 = 999
        A严重度, A分档, _ = _落档(可售天数, cfg["A_分档"], "天数")
    else:
        A_可判 = True
        可售天数 = round(可售库存 / 近30天日均销量)  # 取整数天
        A严重度, A分档, _ = _落档(可售天数, cfg["A_分档"], "天数")

    # B：目标累计
    if 未来N月目标累计_覆盖月数 is None:
        B_可判 = False
        B严重度 = None
        B分档 = "B数据缺失"
    else:
        B_可判 = True
        B严重度, B分档, _ = _落档(未来N月目标累计_覆盖月数, cfg["B_分档"], "月数")

    # 关键数据缺失：A、B 至少一个不可判即视为数据不足
    if not A_可判 or not B_可判:
        return 观察类结果(问题点位="库存积压", 观察类型=观察_数据不足,
                     原因=cfg["数据不足输出"],
                     缺失字段=[k for k, ok in {"近30天日均销量": A_可判,
                                             "未来N月目标累计_覆盖月数": B_可判}.items() if not ok],
                     上下文={"可售天数": 可售天数, "B覆盖月数": 未来N月目标累计_覆盖月数})

    # 交叉规则（此时 A_可判 与 B_可判 均为 True；A严重度/B严重度 None 表示落到"不预警"档）
    降档 = cfg["降档规则"]

    def _降(s):
        return 降档.get(s)  # {S0:S1, S1:S2, S2:null}

    if A严重度 is None and B严重度 is None:
        最终 = None
        规则说明 = "A、B 均不预警"
    elif A严重度 and B严重度:
        最终 = 严重度较高者(A严重度, B严重度)
        规则说明 = f"A={A严重度}, B={B严重度}，取高"
    elif A严重度 and not B严重度:
        最终 = _降(A严重度)
        规则说明 = f"A={A严重度} 有预警但 B 不预警，A 降一档 → {最终}（提示复核未来目标）"
    else:  # not A, B有预警
        最终 = _降(B严重度)
        规则说明 = f"B={B严重度} 有预警但 A 不预警，B 降一档 → {最终}（提示复核淡旺季/目标）"

    if 最终 is None:
        return 严重度判定结果(问题点位="库存积压", 严重度=None,  # type: ignore
                        判定过程=规则说明,
                        分档名称=f"A:{A分档}|B:{B分档}",
                        命中值={"可售天数": 可售天数, "B覆盖月数": 未来N月目标累计_覆盖月数})

    return 严重度判定结果(
        问题点位="库存积压",
        严重度=最终,
        判定过程=f"可售天数 {可售天数}（A:{A分档}），未来覆盖 {未来N月目标累计_覆盖月数:.1f} 月（B:{B分档}）；{规则说明}",
        分档名称=f"A:{A分档}|B:{B分档}",
        命中值={"可售天数": 可售天数, "B覆盖月数": 未来N月目标累计_覆盖月数},
    )


