    默认 = 查默认严重度(问题点位, 参数)
    if 默认:
        return 严重度判定结果(问题点位=问题点位, 严重度=默认,
                          判定过程=f"§3.3 默认严重度表：{默认}",
                          分档名称="默认表")

    if 问题点位 in _专项路由:
        输入 = 输入 or {}
        return _专项路由[问题点位](**输入, 参数=参数)

    return 观察类结果(问题点位=问题点位, 观察类型=观察_数据不足,
                原因=f"未知点位：{问题点位}", 上下文={"提示": "R3 yaml 需补该点位规则"})


