def 查默认严重度(问题点位: str, 参数: dict | None = None) -> str | None:
    """§3.3 固定严重度点位直接查表。跳专项的点位返回 None，由专项函数处理。"""
    if 参数 is None:
        参数 = 加载参数()
    v = 参数["默认严重度表"].get(问题点位)
    if v in ("S0", "S1", "S2"):
        return v
    return None  # 见§3.X 或未定义


# -----------------------------------------------------------------------------
# §3.3.1 共因严重度上调
# -----------------------------------------------------------------------------
def 共因严重度上调(
    初判严重度: str,
    共因数: int,
    问题点位: str,
    根因作用层级: str,
    根因变体重要性: str | None = None,
    参数: dict | None = None,
) -> tuple[str, str]:
    """按 §3.3.1 规则决定是否上调。返回 (上调后严重度, 原因)。"""
    if 参数 is None:
        参数 = 加载参数()
    规则 = 参数["共因严重度上调"]

    if 问题点位 not in 规则["适用点位"]:
        return 初判严重度, f"「{问题点位}」不在共因上调适用清单，维持 {初判严重度}"

    if 共因数 < 规则["阈值_最少共因数"]:
        return 初判严重度, f"共因数 {共因数} < 阈值 {规则['阈值_最少共因数']}，不上调"

    # 变体级根因的层级匹配
    if 根因作用层级 == "变体级":
        if 根因变体重要性 not in ("主要色", None):
            return 初判严重度, f"变体级根因命中「{根因变体重要性}」不计入共因，维持 {初判严重度}"

    # 上调一档，S0 封顶
    上调 = {"S2": "S1", "S1": "S0", "S0": "S0"}
    新档 = 上调.get(初判严重度, 初判严重度)
    if 新档 == 初判严重度:
        return 初判严重度, f"{初判严重度} 已达封顶 {规则['封顶']}，无需上调"
    return 新档, f"共因数 {共因数} ≥ {规则['阈值_最少共因数']}，{初判严重度} → {新档}"


# -----------------------------------------------------------------------------
# §3.6 (1) ACOS 异常
# -----------------------------------------------------------------------------
def 判ACOS异常(
    目标ACOS: float | None,
    近3天平均ACOS: float | None,
    连续天数: int | None,
    近3天累计广告花费: float | None = None,
    近7天日均花费: float | None = None,
    近3天累计点击: int | None = None,
    零销售花费天数: int = 0,
    参数: dict | None = None,
) -> 严重度判定结果 | 观察类结果:
    """§3.6 ACOS 异常。基线为运营在辅助决策 agent 设置的 目标ACOS；连续 ≥3 天 + 样本量门槛。"""
    if 参数 is None:
        参数 = 加载参数()
    cfg = 参数["ACOS异常"]

    # 数据完整性
    缺 = []
    if 目标ACOS is None:
        缺.append("目标ACOS")
    if 近3天平均ACOS is None:
        缺.append("近3天平均ACOS")
    if 连续天数 is None:
        缺.append("连续天数")
    if 缺:
        原因 = f"缺失关键字段 {缺}"
        if "目标ACOS" in 缺:
            原因 += "；请在辅助决策 agent 设置目标 ACOS 后再次巡检"
        return 观察类结果(问题点位="ACOS异常", 观察类型=观察_数据不足,
                     原因=原因, 缺失字段=缺)

    # 连续天数门槛
    if 连续天数 < cfg["连续天数门槛"]:
        return 严重度判定结果(问题点位="ACOS异常", 严重度=None,  # type: ignore
                        判定过程=f"连续 {连续天数} 天 < 门槛 {cfg['连续天数门槛']} 天，不触发",
                        分档名称="连续天数不足", 命中值=连续天数,
                        判定日志={"cfg版本": 参数.get("版本")})

    # 样本量门槛（任一满足）
    门槛条件 = cfg["样本量门槛"]["条件"]
    满足 = []
    未满足 = []
    for 条件 in 门槛条件:
        if 条件["名称"] == "花费门槛":
            if 近3天累计广告花费 is None or 近7天日均花费 is None:
                未满足.append(f"花费门槛（{条件['描述']}）：数据缺失")
                continue
            if 近3天累计广告花费 >= 近7天日均花费 * 3 * 0.5:
                满足.append(条件["名称"])
            else:
                未满足.append(f"花费门槛：{近3天累计广告花费} < {近7天日均花费*3*0.5}")
        elif 条件["名称"] == "点击门槛":
            if 近3天累计点击 is None:
                未满足.append("点击门槛：数据缺失")
                continue
            if 近3天累计点击 >= 20:
                满足.append(条件["名称"])
            else:
                未满足.append(f"点击门槛：{近3天累计点击} < 20")

    if not 满足:
        return 观察类结果(问题点位="ACOS异常", 观察类型=观察_样本不足观察,
                     原因=f"{cfg['样本量不足输出']}: {'; '.join(未满足)}",
                     上下文={"连续天数": 连续天数, "偏离比": (近3天平均ACOS - 目标ACOS) / 目标ACOS if 目标ACOS else None})

    # 偏离比 = (当前 - 目标) / 目标
    偏离比 = (近3天平均ACOS - 目标ACOS) / 目标ACOS
    严重度, 分档名, 档 = _落档(偏离比, cfg["分档"], "偏离比")

    if 严重度 is None:
        return 严重度判定结果(问题点位="ACOS异常", 严重度=None,  # type: ignore
                        判定过程=f"偏离比 {偏离比:.2%}（{分档名}），不预警",
                        分档名称=分档名, 命中值=round(偏离比, 4))

    return 严重度判定结果(
        问题点位="ACOS异常",
        严重度=严重度,
        判定过程=(
            f"近 3 天 ACOS {近3天平均ACOS:.1%}，目标 ACOS {目标ACOS:.1%}，"
            f"偏离目标 {偏离比:.1%}（{分档名}）"
        ),
        分档名称=分档名,
        命中值=round(偏离比, 4),
        判定日志={
            "样本量满足": 满足,
            "连续天数": 连续天数,
            "cfg版本": 参数.get("版本"),
        },
        数据快照=[
            _kv_pct("近 3 天平均 ACOS", 近3天平均ACOS),
            _kv_pct("目标 ACOS", 目标ACOS),
            _kv_pct("偏离幅度", 偏离比),
            _kv_int("已连续天数", 连续天数),
            _kv_money("近 3 天累计广告花费", 近3天累计广告花费),
            _kv_int("近 3 天累计点击", 近3天累计点击),
            _kv_int("广告有花费但零销售天数", 零销售花费天数),
        ],
    )


# -----------------------------------------------------------------------------
# §3.6 (2)(3) 广告花费异常（超出 / 不足）
# -----------------------------------------------------------------------------
def 判广告花费异常(
    目标每日预算: float | None,
    近3天平均花费: float | None,
    连续天数: int | None,
    参数: dict | None = None,
) -> 严重度判定结果 | 观察类结果:
    """§3.6 (2)(3) 广告花费。基线为运营在辅助决策 agent 设置的 目标每日预算；自动判断超出/不足方向。"""
    if 参数 is None:
        参数 = 加载参数()

    if 目标每日预算 is not None and 目标每日预算 <= 0:
        目标每日预算 = None
    缺 = [k for k, v in {"目标每日预算": 目标每日预算, "近3天平均花费": 近3天平均花费,
                        "连续天数": 连续天数}.items() if v is None]
    if 缺:
        原因 = f"缺失字段 {缺}"
        if "目标每日预算" in 缺:
            原因 += "；请在辅助决策 agent 设置目标每日预算后再次巡检"
        return 观察类结果(问题点位="广告花费异常", 观察类型=观察_数据不足,
                     原因=原因, 缺失字段=缺)

    if 连续天数 < 3:
        return 严重度判定结果(问题点位="广告花费异常", 严重度=None,  # type: ignore
                        判定过程=f"连续 {连续天数} 天 < 3 天门槛", 分档名称="连续天数不足",
                        命中值=连续天数)

    if 近3天平均花费 >= 目标每日预算:
        # 超出方向
        cfg = 参数["广告花费异常_超出"]
        偏离比 = (近3天平均花费 - 目标每日预算) / 目标每日预算
        严重度, 分档名, _ = _落档(偏离比, cfg["分档"], "偏离比")
        方向 = "超出"
    else:
        # 不足方向
        cfg = 参数["广告花费异常_不足"]
        偏离比 = (目标每日预算 - 近3天平均花费) / 目标每日预算
        严重度, 分档名, _ = _落档(偏离比, cfg["分档"], "下降比")
        方向 = "不足"

    if 严重度 is None:
        return 严重度判定结果(问题点位="广告花费异常", 严重度=None,  # type: ignore
                        判定过程=f"{方向}方向偏离 {偏离比:.2%}（{分档名}），不预警",
                        分档名称=分档名, 命中值=round(偏离比, 4))

    return 严重度判定结果(
        问题点位="广告花费异常",
        严重度=严重度,
        判定过程=f"近 3 天日均花费 ${近3天平均花费:.2f}，目标每日预算 ${目标每日预算:.2f}，{方向}目标 {偏离比:.1%}（{分档名}）",
        分档名称=分档名,
        命中值=round(偏离比, 4),
        判定日志={"方向": 方向, "连续天数": 连续天数},
        数据快照=[
            _kv_money("近 3 天日均花费", 近3天平均花费),
            _kv_money("目标每日预算", 目标每日预算),
            _kv("偏离方向", 方向),
            _kv_pct("偏离幅度", 偏离比),
            _kv_int("已连续天数", 连续天数),
        ],
    )


